    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="16" fill="#6c5ce7"/>'
           '<path d="M19 47V17h5.5l17 21V17H46v30h-5.5l-17-21v21z" fill="#fff"/></svg>').encode()
