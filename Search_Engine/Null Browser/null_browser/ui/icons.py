"""Vector icon set drawn at runtime from SVG (crisp on any DPI, recolourable for light/dark)."""
from PyQt6.QtCore import QByteArray, Qt
from PyQt6.QtGui import QColor, QIcon, QImage, QPainter, QPen, QPixmap
from PyQt6.QtSvg import QSvgRenderer

from .icon_paths import P  # noqa: E402  (Feather icon geometry, generated by tools/gen_icons.py)

# dock-position glyphs for the DevTools header and the device bar (not part of Feather)
P.setdefault("dock_right", '<rect x="3" y="4" width="18" height="16" rx="2"/><line x1="14" y1="4" x2="14" y2="20"/>')
P.setdefault("dock_bottom", '<rect x="3" y="4" width="18" height="16" rx="2"/><line x1="3" y1="14" x2="21" y2="14"/>')
P.setdefault("rotate", '<polyline points="23 4 23 10 17 10"/><path d="M20.49 15a9 9 0 1 1-2.12-9.36L23 10"/>')
P.setdefault("device", '<rect x="6" y="2" width="12" height="20" rx="2"/><line x1="11" y1="18" x2="13" y2="18"/>')

_cache = {}


def _svg(name, color, stroke=2.0):
    inner = P.get(name, P["globe"]).replace("currentColor", color)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
            f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{inner}</svg>').encode()


def _render(svg, px):
    img = QImage(px, px, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(Qt.GlobalColor.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    QSvgRenderer(QByteArray(svg)).render(p)
    p.end()
    return img


def pixmap(name, color="#000000", size=20, dpr=2.0):
    key = (name, color, size, dpr)
    pm = _cache.get(key)
    if pm is None:
        pm = QPixmap.fromImage(_render(_svg(name, color), int(size * dpr)))
        pm.setDevicePixelRatio(dpr)
        _cache[key] = pm
    return pm


def _alpha(color, a):
    c = QColor(color)
    c.setAlphaF(a)
    return c.name(QColor.NameFormat.HexArgb)


def icon(name, color="#000000", size=20, disabled_color=None):
    ic = QIcon()
    ic.addPixmap(pixmap(name, color, size), QIcon.Mode.Normal)
    ic.addPixmap(pixmap(name, disabled_color or _alpha(color, 0.35), size), QIcon.Mode.Disabled)
    return ic


def spinner_frames(color, size=16, steps=12):
    frames = []
    for i in range(steps):
        img = QImage(size * 2, size * 2, QImage.Format.Format_ARGB32_Premultiplied)
        img.fill(Qt.GlobalColor.transparent)
        p = QPainter(img)
        p.setRenderHint(QPainter.RenderHint.Antialiasing)
        p.translate(size, size)
        p.rotate(i * 360 / steps)
        pen = QPen(QColor(color), size * 0.22)
        pen.setCapStyle(Qt.PenCapStyle.RoundCap)
        p.setPen(pen)
        p.drawArc(int(-size * 0.7), int(-size * 0.7), int(size * 1.4), int(size * 1.4), 0, 270 * 16)
        p.end()
        pm = QPixmap.fromImage(img)
        pm.setDevicePixelRatio(2)
        frames.append(QIcon(pm))
    return frames


_app_icon = None


def app_icon():
    """The Null Browser icon (assets/icon.svg, made by tools/make_icon.py), rendered at every size Windows / Qt asks for."""
    global _app_icon
    if _app_icon is None:
        import os
        path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "assets", "icon.svg")
        try:
            with open(path, "rb") as f:
                svg = f.read()
        except OSError:
            svg = (b'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="16" fill="#6c5ce7"/>'
                   b'<path d="M19 47V17h5.5l17 21V17H46v30h-5.5l-17-21v21z" fill="#fff"/></svg>')
        ic = QIcon()
        for px in (16, 20, 24, 32, 40, 48, 64, 128, 256):
            ic.addPixmap(QPixmap.fromImage(_render(svg, px)))
        _app_icon = ic
    return _app_icon
